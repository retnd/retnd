#!/usr/bin/env bash
# Shift the version everywhere retnd keeps it, in the working tree (#1375).
#
#   bash scripts/release/bump-version.sh <new-version>
#
# The old version is image.tag in distribution/packaging/canonical.json. The
# files are the ones the previous prep commit (the one whose subject is
# "Prepare <old>") touched, minus the generated or history files: those are
# regenerated or left alone below. That is the convention the 0.7.2 cut used
# ("only on lines the previous prep commit changed"), made executable.
#
#  * canonical.json: image.tag, image.reference and image.published=false
#    (the candidate has no registry identity yet).
#  * every other file in that set: lines containing <old> as a whole version
#    token (not 0.7.20, not 10.7.2) become <new>. Lines carrying an
#    "<older>-><old>" or "<older> to <old>" pair are left for a human.
#  * left alone ON PURPOSE: CHANGELOG.md (history), container/release-manifest.json,
#    core/tests/deploymentdiff/testdata/digests.txt and provenance/* (generated by
#    record-release-hashes.sh and `go run ./cmd/provenance -write`; the script
#    runs the second when RELEASE_BUMP_PROVENANCE is not 0), and *.lock/package-lock
#    files.
# It prints the lines still naming the old version, so what is left is a list
# you can read, not a surprise.
set -euo pipefail
new="${1:-}"
[ -n "$new" ] || { echo "bump-version: usage: bump-version.sh <new-version>" >&2; exit 2; }
root="$(git rev-parse --show-toplevel)"; cd "$root"
canon=distribution/packaging/canonical.json
old="$(sed -n 's/^ *"tag": *"\([^"]*\)".*/\1/p' "$canon" | head -n 1)"
[ -n "$old" ] || { echo "bump-version: no image.tag in $canon" >&2; exit 2; }
[ "$old" != "$new" ] || { echo "bump-version: $canon is already at $new" >&2; exit 2; }
prep="$(git log -1 --format=%H -E --grep="^Prepare $old\$" HEAD || true)"
[ -n "$prep" ] || { echo "bump-version: no commit titled 'Prepare $old' in history, so there is no file set to follow." >&2; exit 2; }

q_old="$(printf '%s' "$old" | sed 's/[.[\*^$/-]/\\&/g')"
sed -i.bak \
  -e "s/^\( *\"tag\": *\"\)[^\"]*\"/\1$new\"/" \
  -e "s/^\( *\"reference\": *\"[^\"]*:\)[^\":]*\"/\1$new\"/" \
  -e "s/^\( *\"published\": *\)true/\1false/" "$canon"
rm -f "$canon.bak"

git diff-tree --root --no-commit-id --name-only -r "$prep" | while IFS= read -r f; do
  case "$f" in
    CHANGELOG.md|container/release-manifest.json|core/tests/deploymentdiff/testdata/digests.txt|provenance/*|*package-lock.json|*.lock|"$canon") continue ;;
  esac
  [ -f "$f" ] || continue
  sed -i.bak -E "/(->|→| to )[^0-9]*${q_old}|${q_old}[^0-9]*(->|→)/!s/(^|[^0-9A-Za-z.])${q_old}([^0-9A-Za-z.]|\.[^0-9]|\$)/\1$new\2/g" "$f"
  rm -f "$f.bak"
done

if [ "${RELEASE_BUMP_PROVENANCE:-1}" != 0 ]; then
  ( cd distribution && go run ./cmd/provenance -write )
fi

echo "bump-version: $old -> $new. Lines still naming $old (left on purpose, read them):"
git grep -nI -F "$old" -- . ':!CHANGELOG.md' ':!provenance' ':!container/release-manifest.json' ':!docs/site' ':!.claude' | head -40 || true
